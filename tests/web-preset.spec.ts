/**
 * Preset-sync coverage: `scripts/make-web-preset.mjs` regenerates the shipped
 * `standard-rollover` preset declaration from a shipped `standard` composition,
 * fails loud when the shipped shape drifts or flags are invalid, and the
 * committed declaration always matches a fresh sync. The bundle's patch list
 * and root patch are checked as text against the host's declaration format.
 *
 * The script runs as a real subprocess against temp directories, so this
 * suite covers the shipped artifact rather than an import of it.
 *
 * @module tests/web-preset
 */

import { execFileSync } from 'node:child_process'
import { existsSync, mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const script = fileURLToPath(new URL('../scripts/make-web-preset.mjs', import.meta.url))
const repoRoot = resolve(dirname(script), '..')

/** The shipped `compaction-basic` row as the fixture carries it (rows at column 0). */
const BASIC_ROW_TEXT = `    - id: compaction-basic\n      name: '@deepseek-ai/dsh-compaction-basic'`

/** Indent the declaration adds under `plugins:` (keep in step with the generator). */
const PLUGINS_INDENT = 10

/** The `plugins:` key line as the declaration writes it, through its newline. */
const PLUGINS_KEY = '        plugins:\n'

/** Leading comment of the engine row in the dedented body. */
const ENGINE_MARKER = '    # Generated by dsh-context-rollover'

const pad = (width: number): string => ' '.repeat(width)

/** Minimal shipped-shape fixture: surrounding rows plus the real compaction group. */
function standardFixture(): string {
  return `# fixture standard preset
- id: persona
  name: '@deepseek-ai/dsh-persona'

# \`compaction-basic\` reads \`toolResultPrune\` through \`ctx.get\`, so the pruner must
# share this realm rather than sit outside it.
- id: compaction
  name: cordis:group
  group: true
  isolate:
    compaction: true
    toolResultPruner: true
  config:
    - id: compaction-basic
      name: '@deepseek-ai/dsh-compaction-basic'

    - id: command-compact
      name: '@deepseek-ai/dsh-command-compact'

    - id: tool-result-pruner
      name: '@deepseek-ai/dsh-compaction-tool-result-pruner'
      config:
        thresholdChars: 8192
`
}

/** Scratch dirs for one run: a presets root holding `standard/` and an out dir. */
function scratch(fixture: string): { presetsDir: string; outDir: string; cleanup: () => void } {
  // Temp dirs inside the repo keep every scratch path under the checkout.
  const base = mkdtempSync(join(repoRoot, 'tmp-scratch-'))
  const presetsDir = join(base, 'presets')
  const outDir = join(base, 'out')
  mkdirSync(join(presetsDir, 'standard'), { recursive: true })
  writeFileSync(join(presetsDir, 'standard', 'agent.cordis.yml'), fixture)
  return { presetsDir, outDir, cleanup: () => { rmSync(base, { recursive: true, force: true }) } }
}

/** Run the script, returning stdout; throws (with status/stderr) on failure. */
function run(args: readonly string[]): string {
  return execFileSync(process.execPath, [script, ...args], { encoding: 'utf8' })
}

/** The package name, read from package.json, that the engine row must carry. */
function packageName(): string {
  return (JSON.parse(readFileSync(join(repoRoot, 'package.json'), 'utf8')) as { name: string }).name
}

/** The committed declaration's text. */
function committedDeclaration(): string {
  return readFileSync(join(repoRoot, 'presets', 'standard-rollover.patch.yml'), 'utf8')
}

/**
 * Remove the declaration indent from every non-blank line. A line without it
 * throws, so a re-indented or mis-nested row cannot pass as a fixture copy.
 * @param text - text whose non-blank lines all carry `width` leading spaces.
 * @param width - the declaration indent to remove.
 * @returns the text with that indent removed.
 */
function dedent(text: string, width: number): string {
  return text.split('\n').map((line) => {
    if (line === '') return line
    if (!line.startsWith(pad(width))) throw new Error(`line not indented by ${width}: ${JSON.stringify(line)}`)
    return line.slice(width)
  }).join('\n')
}

/**
 * The committed declaration's plugin rows, dedented to the fixture's layout.
 * @param declaration - the declaration text to read.
 * @returns the rows, from `plugins:` to the end, at column 0.
 */
function committedRows(declaration = committedDeclaration()): string {
  const at = declaration.indexOf(PLUGINS_KEY)
  if (at === -1) throw new Error('declaration has no plugins: key')
  return dedent(declaration.slice(at + PLUGINS_KEY.length), PLUGINS_INDENT)
}

describe('make-web-preset', () => {
  it('derives standard-rollover with the engine row and untouched surroundings', () => {
    const { presetsDir, outDir, cleanup } = scratch(standardFixture())
    try {
      run(['--presets-dir', presetsDir, '--out-dir', outDir, '--retain-tokens', '12000'])
      const declaration = readFileSync(join(outDir, 'standard-rollover.patch.yml'), 'utf8')
      expect(declaration).not.toContain(`name: '@deepseek-ai/dsh-compaction-basic'`)
      expect(declaration).toContain('- id: context-rollover')
      // The engine is named by its installed package, never by a file path.
      expect(declaration).toContain(`name: '${packageName()}'`)
      expect(declaration).not.toContain('lib/index.js')
      expect(declaration).toContain('thresholdRatio: 0.9')
      expect(declaration).toContain('retainTokens: 12000')
      expect(declaration).not.toContain('retainRatio')
      // The preset row owns its model-facing tools and guidance explicitly.
      expect(declaration).toContain(`modelSurface: 'always'`)
      // Untouched rows survive around the swap, shifted by the declaration indent.
      expect(declaration).toContain(`${pad(10)}- id: persona\n${pad(12)}name: '@deepseek-ai/dsh-persona'`)
      expect(declaration).toContain(`${pad(14)}- id: command-compact\n${pad(16)}name: '@deepseek-ai/dsh-command-compact'`)
      // One declaration file; no legacy directory is written.
      expect(existsSync(join(outDir, 'standard-rollover'))).toBe(false)
      expect(declaration).toContain(
        `- insert:\n    - id: preset-standard-rollover\n      name: '@deepseek-ai/dsh-agent-preset'\n`
        + `      config:\n        id: standard-rollover\n`,
      )
      expect(declaration).toContain(`        name: 'Standard + rollover (experimental)'\n`)
      expect(declaration).toContain(`        order: 2\n        plugins:\n`)
    } finally {
      cleanup()
    }
  })

  it('fails loud when the shipped row is absent', () => {
    const { presetsDir, outDir, cleanup } = scratch('# no compaction here\n- id: persona\n  name: x\n')
    try {
      expect(() => run(['--presets-dir', presetsDir, '--out-dir', outDir])).toThrow(/compaction-basic row/)
    } finally {
      cleanup()
    }
  })

  it('fails loud when the shipped row gains an unexpected config block', () => {
    const changed = standardFixture().replace(
      `    - id: compaction-basic\n      name: '@deepseek-ai/dsh-compaction-basic'\n`,
      `    - id: compaction-basic\n      name: '@deepseek-ai/dsh-compaction-basic'\n      config:\n        future: true\n`,
    )
    const { presetsDir, outDir, cleanup } = scratch(changed)
    try {
      expect(() => run(['--presets-dir', presetsDir, '--out-dir', outDir])).toThrow(/unexpected config block/)
    } finally {
      cleanup()
    }
  })

  it('rejects out-of-range flags', () => {
    const { presetsDir, outDir, cleanup } = scratch(standardFixture())
    try {
      expect(() => run(['--presets-dir', presetsDir, '--out-dir', outDir, '--threshold-ratio', '2']))
        .toThrow(/in \(0, 1\]/)
    } finally {
      cleanup()
    }
  })

  it('committed preset matches a fresh sync of the repo standard fixture', () => {
    // Temp dir inside the repo, removed in the finally block below.
    const outDir = mkdtempSync(join(repoRoot, 'tmp-sync-'))
    try {
      // The source composition is checked in here rather than read from a
      // sibling harness checkout: the running host ships its presets as
      // `.patch.yml` declarations, so no `standard/agent.cordis.yml` exists
      // to sync from. The fixture carries exactly the shipped `standard`
      // rows (verified row-for-row against the host's own declaration), so
      // this still proves the committed declaration is a fresh generation.
      run(['--presets-dir', join(repoRoot, 'tests', 'fixtures'), '--out-dir', outDir])
      const fresh = readFileSync(join(outDir, 'standard-rollover.patch.yml'), 'utf8')
      expect(fresh).toBe(committedDeclaration())
    } finally {
      rmSync(outDir, { recursive: true, force: true })
    }
  })

  it('the repo fixture is the shipped standard shape the generator expects', () => {
    // The sync's anchor row is the contract between the fixture and the
    // generator: if either drifts, the sync above fails loud instead of the
    // committed declaration silently becoming un-reproducible.
    const source = readFileSync(join(repoRoot, 'tests', 'fixtures', 'standard', 'agent.cordis.yml'), 'utf8')
    expect(source).toContain(
      `- id: compaction\n  name: cordis:group\n  group: true\n  isolate:\n`
      + `    compaction: true\n    toolResultPruner: true\n  config:\n`,
    )
    expect(source.match(/^ {4}- id: compaction-basic\n {6}name: '@deepseek-ai\/dsh-compaction-basic'$/gm)).toHaveLength(1)
    // The declaration's rows are the fixture's own bytes with only the engine
    // row swapped: everything before the swap must survive untouched.
    const [sourceHead] = source.split('    - id: compaction-basic')
    const [committedHead] = committedRows().split(ENGINE_MARKER)
    expect(committedHead).toBe(sourceHead)
  })

  it('ships the preset as a host-format declaration file, not a legacy directory', () => {
    const declaration = committedDeclaration()
    const firstRow = declaration.split('\n').find(line => line !== '' && !line.startsWith('#'))
    expect(firstRow).toBe('- insert:')
    expect(declaration).toContain(
      `    - id: preset-standard-rollover\n      name: '@deepseek-ai/dsh-agent-preset'\n      config:\n`
      + `        id: standard-rollover\n`,
    )
    expect(existsSync(join(repoRoot, 'presets', 'standard-rollover'))).toBe(false)
  })

  it('lists the preset declaration in the bundle patch list after the root patch', () => {
    const manifest = JSON.parse(readFileSync(join(repoRoot, 'package.json'), 'utf8')) as {
      dsh: { bundle: { patch: unknown } }
    }
    expect(manifest.dsh.bundle.patch).toEqual(['./cordis.patch.yml', './presets/standard-rollover.patch.yml'])
  })

  it('keeps the root patch free of a presets-root registration', () => {
    // The host's registry accepts only `default` and `selectedDefault`, and it
    // is not registered under the id this row used to patch. The presets-root
    // keys have no place in the declaration format, so the root patch must not carry them.
    const patch = readFileSync(join(repoRoot, 'cordis.patch.yml'), 'utf8')
    expect(patch).not.toContain('id: agent-presets')
    expect(patch).not.toContain('roots:')
    expect(patch).not.toContain('includeShippedRoot')
    expect(patch).not.toContain('includeUserRoot')
  })

  it('names the rollover engine by its installed package, not a file path', () => {
    const declaration = committedDeclaration()
    expect(declaration).toMatch(
      new RegExp(`^ {14}- id: context-rollover\\n {16}name: '${packageName()}'$`, 'm'),
    )
    expect(declaration).not.toMatch(/name: '\.\.?\//)
  })

  it('keeps the declaration body equal to the fixture with only the engine row swapped', () => {
    const fixture = readFileSync(join(repoRoot, 'tests', 'fixtures', 'standard', 'agent.cordis.yml'), 'utf8')
    const parts = fixture.split(BASIC_ROW_TEXT)
    expect(parts).toHaveLength(2)
    const [fixtureHead, fixtureTail] = parts
    const body = committedRows()
    const engine = body.match(/    # Generated by dsh-context-rollover[\s\S]*?modelSurface: 'always'/)
    if (engine === null || engine.index === undefined) throw new Error('declaration has no engine row')
    // The tail carries the plan-mode prompt text, so this also pins the prompt bytes.
    expect(body.slice(0, engine.index)).toBe(fixtureHead)
    expect(body.slice(engine.index + engine[0].length)).toBe(fixtureTail)
  })
})
